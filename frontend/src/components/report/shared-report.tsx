"use client";

import { Link2Off, Printer } from "lucide-react";
import Link from "next/link";
import { useParams } from "next/navigation";

import { Logo } from "@/components/brand/logo";
import { ThemeToggle } from "@/components/layout/theme-toggle";
import { ButtonLink } from "@/components/ui/button";
import { Badge, EmptyState, Skeleton } from "@/components/ui/primitives";
import { ConfidenceBadge, EvidenceStrength } from "@/components/ui/score";
import { useApi } from "@/lib/api";
import type { OpportunityReport } from "@/lib/types";
import { formatDate, plural } from "@/lib/utils";

import { ReportTabs } from "./report-body";
import { useSourceIndex } from "./report-view";
import { BRAND } from "@/lib/brand";

export function SharedReport() {
  const { token } = useParams<{ token: string }>();
  const { data: r, error } = useApi<OpportunityReport>(`/share/${token}`);
  const index = useSourceIndex(r);

  return (
    <div className="min-h-dvh">
      <header className="border-b border-border" data-print-hide>
        <div className="mx-auto flex h-16 max-w-7xl items-center justify-between px-4 sm:px-6 lg:px-10">
          <Link href="/"><Logo /></Link>
          <div className="flex items-center gap-2">
            <ThemeToggle />
            <ButtonLink href={`/print/s/${token}`} external variant="ghost" size="sm"><Printer />Save as PDF</ButtonLink>
            <ButtonLink href="/discover" size="sm">Try {BRAND.name}</ButtonLink>
          </div>
        </div>
      </header>
      <main className="mx-auto max-w-7xl px-4 py-8 sm:px-6 md:py-10 lg:px-10">
        {error ? (
          <EmptyState icon={<Link2Off />} title="This report isn’t available" description={error.message} action={<ButtonLink href="/">Go to {BRAND.name}</ButtonLink>} />
        ) : !r ? (
          <div className="space-y-4"><Skeleton className="h-10 w-2/3" /><Skeleton className="h-64" /></div>
        ) : (
          <>
            <div className="mb-8">
              <div className="mb-3 flex flex-wrap gap-1.5">
                <Badge>Shared report</Badge>
                <Badge tone="primary">{r.industry}</Badge>
                <Badge>{r.location_label}</Badge>
                <ConfidenceBadge confidence={r.confidence} />
              </div>
              <h1 className="max-w-3xl text-[28px] font-semibold leading-tight tracking-tight sm:text-[34px]">{r.title}</h1>
              <div className="mt-3 flex flex-wrap items-center gap-x-4 gap-y-1 text-sm text-muted">
                <EvidenceStrength value={r.evidence_strength} />
                <span>{plural(r.supporting_count, "source")} back this up</span>
                <span>Researched {formatDate(r.discovery.created_at)}</span>
              </div>
            </div>
            {r.plain_summary && <p className="-mt-2 mb-8 max-w-3xl text-[17px] leading-relaxed text-muted">{r.plain_summary}</p>}
            <ReportTabs report={r} index={index} />
            <footer className="mt-14 border-t border-border pt-6 text-xs text-subtle">
              Generated by {BRAND.name} from {r.discovery.stats.analyzed ?? r.sources.length} public sources. Scores are a guide, not a prediction.
              Always review the original sources before making decisions.
            </footer>
          </>
        )}
      </main>
    </div>
  );
}
